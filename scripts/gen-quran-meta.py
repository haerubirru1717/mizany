#!/usr/bin/env python3
"""Generate src/data/quranMeta.generated.ts (METADATA only, never Qur'an text).

Sources (cross-checked, the script aborts on any mismatch):
  - EQuran.id v2 /api/v2/surat  -> surah number, Latin name, meaning, ayah count, place
  - Al Quran Cloud /v1/meta      -> ayah count (cross-check), 604 page starts, 30 juz starts

Usage: python3 scripts/gen-quran-meta.py
"""
import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'data', 'quranMeta.generated.ts')


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'mizany-meta-gen'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


eq = fetch('https://equran.id/api/v2/surat')['data']
meta = fetch('https://api.alquran.cloud/v1/meta')['data']
ms = meta['surahs']['references']
pages = meta['pages']['references']
juzs = meta['juzs']['references']

assert len(eq) == 114 == len(ms), 'surah count mismatch'
total = 0
for a, b in zip(eq, ms):
    assert a['nomor'] == b['number'], a['nomor']
    assert a['jumlahAyat'] == b['numberOfAyahs'], f"ayah count mismatch surah {a['nomor']}"
    total += a['jumlahAyat']
assert total == 6236, total
assert len(pages) == 604 and len(juzs) == 30


def key(r):
    return (r['surah'], r['ayah'])


assert all(key(pages[i]) < key(pages[i + 1]) for i in range(603))
assert all(key(juzs[i]) < key(juzs[i + 1]) for i in range(29))
assert key(pages[0]) == (1, 1) and key(juzs[0]) == (1, 1)

lines = [
    '// AUTO-GENERATED by scripts/gen-quran-meta.py — jangan diedit manual.',
    '// Sumber: nama & arti surat dari EQuran.id v2 (data Kemenag RI);',
    '// jumlah ayat dicek silang dengan Al Quran Cloud /v1/meta (total 6.236 ayat);',
    '// batas halaman (604, Mushaf Madinah) & Juz (30) dari Al Quran Cloud /v1/meta.',
    "// File ini hanya berisi METADATA (nama, nomor, jumlah ayat, batas halaman/Juz), BUKAN teks Al-Qur'an.",
    '',
    '/** [nomor, namaLatin, arti, jumlahAyat, tempatTurun] */',
    "export const SURAH_ROWS: ReadonlyArray<readonly [number, string, string, number, 'Mekah' | 'Madinah']> = [",
]
for a in eq:
    place = 'Mekah' if a['tempatTurun'].lower().startswith('mek') else 'Madinah'
    lines.append(
        f"  [{a['nomor']}, {json.dumps(a['namaLatin'], ensure_ascii=False)}, "
        f"{json.dumps(a['arti'], ensure_ascii=False)}, {a['jumlahAyat']}, '{place}'],"
    )
lines += [']', '', '/** Ayat pertama tiap halaman Mushaf 1..604, format [surah, ayat]. */',
          'export const PAGE_STARTS: ReadonlyArray<readonly [number, number]> = [']
row = [f"[{p['surah']},{p['ayah']}]" for p in pages]
for i in range(0, len(row), 10):
    lines.append('  ' + ', '.join(row[i:i + 10]) + ',')
lines += [']', '', '/** Ayat pertama tiap Juz 1..30, format [surah, ayat]. */',
          'export const JUZ_STARTS: ReadonlyArray<readonly [number, number]> = [']
row = [f"[{j['surah']},{j['ayah']}]" for j in juzs]
for i in range(0, 30, 10):
    lines.append('  ' + ', '.join(row[i:i + 10]) + ',')
lines.append(']')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('OK', total, 'ayat ->', OUT)
